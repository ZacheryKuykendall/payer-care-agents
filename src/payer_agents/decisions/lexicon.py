#: Logit offsets applied before any evidence is considered.
#:
#: ``cannot_tell`` starts ahead so a request with no recognisable cue abstains
#: instead of guessing. ``Routine`` starts well ahead because urgency is a
#: four-level scale and the probability-weighted score of a near-uniform
#: distribution is around 1.5 -- which would read as "Elevated" for a message that
#: said nothing urgent at all. A strong Routine prior is what keeps the baseline
#: near zero so the escalation threshold means something.
